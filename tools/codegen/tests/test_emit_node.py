def test_typechecks(files: dict[str, str], tmp_path: Path) -> None:
    package = tmp_path / "node"
    shutil.copytree(
        node.PACKAGE, package, ignore=shutil.ignore_patterns("node_modules", "dist", "generated")
    )
    (package / "node_modules").symlink_to(node.PACKAGE / "node_modules")
    for path, content in files.items():
        target = tmp_path / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    (package / "usage.ts").write_text(USAGE)
    (package / "tsconfig.check.json").write_text(
        '{"extends": "./tsconfig.json", "include": ["src", "usage.ts"]}'
    )

    result = subprocess.run(
        [str(package / "node_modules" / ".bin" / "tsc"), "-p", "tsconfig.check.json"],
        cwd=package,
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 0, result.stdout + result.stderr
