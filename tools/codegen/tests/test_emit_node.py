import shutil
import subprocess
from pathlib import Path

import pytest

from whitebird_codegen.build import load
from whitebird_codegen.emitters import node

FIXTURE = Path(__file__).parent / "fixtures" / "spec"

pytestmark = pytest.mark.skipif(
    shutil.which("node") is None or shutil.which("npm") is None or not node.BIOME.exists(),
    reason="needs Node.js and `npm ci` in node/",
)

# Exercises the fixture API the way a user would; `tsc` must accept it.
USAGE = """\
import {
  Category,
  type Event,
  type OrderStatus,
  type Page,
  Priority,
  type Product,
  type ServerSentEvent,
  Whitebird,
} from './src/index.js';

const client = new Whitebird({ environment: 'demo', baseUrls: { shop: 'https://shop.test' } });

export async function usage(): Promise<void> {
  const first: Page<Product> = await client.products.list({ size: 10, category: Category.BOOKS });
  for await (const product of client.products.list({ tags: ['new'], labels: ['a'] })) {
    const id: number = product.id;
    const discount: number | null | undefined = product.discount;
    const price: string | undefined = product.price;
    console.log(id, discount, price, first.totalElements);
  }
  const featured: Page<Product> = await client.products.featured();
  const product: Product = await client.products.get(1);
  const removed: void = await client.products.delete(product.id);
  const order = await client.orders.create({
    productId: 1,
    quantity: 2,
    priority: Priority.N1,
    note: undefined,
    'X-Request-Id': 'request-1',
  });
  const total: string | undefined = order.total;
  const status: OrderStatus = order.status;
  const future: OrderStatus = 'NOT_YET_KNOWN';
  for await (const found of client.orders.search({ statuses: ['NEW'], size: 5 })) {
    console.log(found.id);
  }
  const pdf: Uint8Array = await client.orders.documents.receipt('o-1', { format: 'PDF' });
  await client.orders.withdraw('o-1', { address: 'addr' }, { timeout: 5000 });
  const balances: Record<string, string> = await client.balances.get();
  const text: string = await client.profile.uploadAvatar({
    file: new Uint8Array([1]),
    crop: { size: 64 },
    caption: { text: 'hi' },
  });
  const pair = await client.session.changePassword({ oldPassword: 'a', newPassword: 'b' });
  const loggedOut: void = await client.session.logout();
  const cleared: void = await client.cart.clear();
  const tickers = await client.tickers.list({ symbol: 'BTCUSDT' });
  const stream = client.events.stream({ signal: AbortSignal.timeout(1000) });
  for await (const event of stream) {
    const typed: ServerSentEvent<Event> = event;
    console.log(typed.data.type);
  }
  // @ts-expect-error format is required
  await client.orders.documents.receipt('o-1', {});
  // @ts-expect-error quantity is required
  await client.orders.create({ productId: 1 });
  console.log(removed, status, future, pdf, balances, text, cleared, tickers[0]?.lastPrice);
  console.log(featured, total, pair.access_token, loggedOut);
}
"""


@pytest.fixture(scope="module")
def files() -> dict[str, str]:
    return node.emit(load(FIXTURE))


def source(files: dict[str, str], name: str) -> str:
    return files[f"{node.GENERATED}/{name}"]


def test_layout(files: dict[str, str]) -> None:
    assert sorted(path.removeprefix(f"{node.GENERATED}/") for path in files) == [
        "index.ts",
        "models.ts",
        "resources/balances.ts",
        "resources/cart.ts",
        "resources/events.ts",
        "resources/orders.ts",
        "resources/products.ts",
        "resources/profile.ts",
        "resources/session.ts",
        "resources/tickers.ts",
        "services.ts",
        "shapes.ts",
    ]
    assert all(
        content.startswith("// Code generated by whitebird-codegen. DO NOT EDIT.\n")
        for content in files.values()
    )


def test_is_deterministic(files: dict[str, str]) -> None:
    assert node.emit(load(FIXTURE)) == files


def test_models(files: dict[str, str]) -> None:
    models = source(files, "models.ts")
    assert "export type OrderStatus = 'NEW' | 'FILLED' | 'CANCELLED' | (string & {});" in models
    assert "export type Priority = 1 | 2 | 3 | (number & {});" in models
    assert "IN_PROGRESS: 'in-progress'," in models
    assert "discount?: number | null;" in models
    # Decimals are exact strings; values that are sent also take numbers and `undefined`.
    assert "price?: string;" in models
    assert "total?: string;" in models
    assert "productId: number;\n  quantity: number;" in models
    assert "note?: string | undefined;" in models
    assert "file?: Blob | Uint8Array | undefined;" in models
    assert "@defaultValue `'web'`, sent when not set" in models
    assert "/** @deprecated */\n  legacyCode?: string;" in models
    assert "Inferred from the web application" in models
    assert "export interface ProductDimensions {" in models


def test_resources(files: dict[str, str]) -> None:
    products = source(files, "resources/products.ts")
    signature = "list(params: ProductsListParams = {}, options?: RequestOptions)"
    assert f"{signature}: Paginator<Product>" in products
    assert "auth: false" in products
    assert "@deprecated" in products
    assert "defaults: { query: { page: 0, size: 20, sort: 'name,asc' } }" in products
    assert "responseShape: { content: ['array', 'Product'] }" in products
    # `labels[]` is sent for the `labels` member.
    assert "const { labels, ...query } = params;" in products
    assert "query: { ...query, 'labels[]': labels }" in products
    assert "  labels?: string[] | undefined;" in products
    assert "path: '/api/v1/products/{productId}',\n        pathParams: { productId }," in products
    # A page response without a page parameter is a single page.
    assert "featured(options?: RequestOptions): Promise<Page<Product>>" in products

    orders = source(files, "resources/orders.ts")
    assert "readonly documents = new OrdersDocumentsResource(this._client);" in orders
    assert "const { 'X-Request-Id': xRequestId, ...body } = params;" in orders
    assert "pageIn: 'body'" in orders
    assert "bodyType: 'form'" in orders
    assert "@experimental" in orders
    assert "export interface OrdersCreateParams extends OrderRequest {" in orders
    assert "mfa: 'WITHDRAWAL'" in orders
    assert "defaults: { body: { channel: 'web' } }" in orders
    assert "responseShape: 'Order'" in orders

    cart = source(files, "resources/cart.ts")
    assert "clear(options?: RequestOptions): Promise<void> {" in cart
    assert "body: {}" in cart
    profile = source(files, "resources/profile.ts")
    assert "partTypes: { crop: 'application/json', caption: 'text/plain' }" in profile

    session = source(files, "resources/session.ts")
    assert "session: 'end'" in session
    assert "session: 'replace'" in session
    assert "responseShape: ['map', '#']" in source(files, "resources/balances.ts")

    assert "envelope: 'retcode'" in source(files, "resources/tickers.ts")
    assert "AsyncIterable<ServerSentEvent<Event>>" in source(files, "resources/events.ts")


