"""Helpers shared by the emitters."""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from typing import Any

import jinja2

from .. import naming

HEADER = "Code generated by whitebird-codegen. DO NOT EDIT."
TEMPLATES = Path(__file__).resolve().parent.parent / "templates"


def environment(language: str, **filters: Any) -> jinja2.Environment:
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(TEMPLATES / language),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        undefined=jinja2.StrictUndefined,
        autoescape=False,
    )
    env.filters.update(
        snake=naming.snake,
        camel=naming.camel,
        pascal=naming.pascal,
        upper_snake=naming.upper_snake,
        **filters,
    )
    env.globals["HEADER"] = HEADER
    return env


def pipe(command: list[str], source: str, cwd: Path | None = None) -> str:
    """Runs a formatter that reads source on stdin and writes the result to stdout."""
    if shutil.which(command[0]) is None:
        raise RuntimeError(f"{command[0]} is required to format generated code")
    result = subprocess.run(
        command, input=source, capture_output=True, text=True, cwd=cwd, check=False
    )
    if result.returncode != 0:
        raise RuntimeError(f"{' '.join(command)} failed:\n{result.stderr}")
    return result.stdout


def docstring_lines(*parts: str | None) -> list[str]:
    """Joins summary and description into trimmed lines, dropping duplicates and blanks."""
    seen: list[str] = []
    for part in parts:
        text = (part or "").strip()
        if text and text not in seen:
            seen.append(text)
    return "\n\n".join(seen).splitlines()
